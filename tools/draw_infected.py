"""Build our own infected (assets-debt I1) from our own pixelgen reference.

The reference (generated by pixelgen from our prompt, Apache-2.0 model, sidecar beside it)
gives only the layout: which pixel is head, shirt, arm, trousers or line. Everything you see
is ours: the materials are re-coloured on our ramps, shaded lit from the top left, given
coloured inner lines where materials meet and a one-pixel dark contour, and cut to the
player's height. The result goes into Tandem for the hand pass, and is checked with
`tools/critique_sprite.py`.

    python3 tools/draw_infected.py shambler <reference_lock.png> out.png
"""
from __future__ import annotations

import sys

from PIL import Image

OUT = "#030102"
RAMPS = {  # dark → light
    "skin":   ["#34432f", "#526848", "#71886a", "#97ab87"],
    "skin_far": ["#2a3526", "#34432f", "#526848", "#71886a"],   # the arm in shadow
    # hair, belt/shoes and trousers share one near-black and differ in hue above it
    "hair":   ["#141418", "#2a2022", "#3b2e30", "#4e3f41"],
    "shirt":  ["#2e1226", "#55203f", "#7e3361", "#a8508a"],
    "belt":   ["#141418", "#1e1d22", "#2a282e", "#36343a"],
    "pants":  ["#141418", "#222838", "#303a50", "#414c63"],
    "shoe":   ["#141418", "#1e1d22", "#2a282e", "#36343a"],
    "blood":  ["#3a0b0e", "#5e1418", "#86211f", "#a8342a"],
    "mouth":  ["#1a0a0c", "#2c1214", "#3e1a1c", "#3e1a1c"],
    "eye":    ["#b3ab78", "#b3ab78", "#d6cf98", "#d6cf98"],
    "lid":    ["#34432f", "#34432f", "#34432f", "#34432f"],      # a shut eye
    # the horde: a teal sequin party dress, glitter on it, a neon cyan earring and bracelet
    "dress":  ["#0f2a2e", "#16474c", "#1f6b70", "#2f9096"],
    "sequin": ["#5fd3d6", "#5fd3d6", "#5fd3d6", "#5fd3d6"],
    "sparkle": ["#b8f6f2", "#b8f6f2", "#b8f6f2", "#b8f6f2"],
    "jewel":  ["#05d9e8", "#05d9e8", "#05d9e8", "#05d9e8"],
}
FLAT = {"mouth", "eye", "lid", "line", "sequin", "sparkle", "jewel"}


# --- the shambler: regions of reference 1941657839 (see the README in assets/raw/ref_infected)
def shambler_regions(c: str, x: int, y: int) -> str | None:
    """Material for a reference pixel of colour c at (x, y), in the cropped reference."""
    line = {"#171520", "#1d212b", "#0a0612"}
    if c in line:
        if y <= 22 and 24 <= x <= 32 and y >= 20:
            return "mouth"            # the open jaw is drawn as line in the reference
        return "line"
    if c == "#fcefcd":
        return "eye"
    if c == "#ff2a6d":
        return "blood"
    if y >= 76:
        return "shoe"
    if y <= 21:
        if c in ("#475367", "#444f64", "#3e2654", "#2c202e"):
            return "hair"
        return "skin"
    if c in ("#3e2654", "#2c202e") and y >= 50:
        return "belt" if y <= 51 and c == "#2c202e" else "pants"
    if c == "#2c202e" and y <= 22:
        return "mouth"
    if c == "#a8a184":
        if y >= 52 and 8 < x < 13:
            return "pants"            # hem hidden behind the hand: trousers once the hand moves
        if y >= 35 and x <= 8:
            return "skin"             # near forearm and hand
        if y <= 25 and x >= 22:
            return "skin"             # neck and chin
        return "shirt"
    if c in ("#475367", "#444f64"):
        if x >= 22 and y >= 34:
            return "skin_far"         # far arm, in shadow
        if y <= 25:
            return "skin_far"         # nape under the hair
        return "shirt"
    if c == "#3e2654":
        return "shirt"
    return "shirt"


# --- the horde: regions of reference 1986989899, cleaned at --pixel-width 11
def horde_regions(c: str, x: int, y: int) -> str | None:
    if c == "#475367" and y >= 80:
        return None                   # the shadow under her feet: our sprites carry none
    if c in ("#0a0612", "#1d212b"):
        return "line"
    if c in ("#171520", "#2c202e"):
        if y >= 77:
            return "shoe"             # black heels
        return "hair" if y < 30 else "line"
    if c == "#fcefcd":
        return "eye" if y < 20 else "sparkle"
    if c == "#05d9e8":
        return "jewel"
    if c in ("#ff2a6d", "#e3966f", "#f7d8a6"):
        if y < 36 and x >= 22:
            return "mouth" if y < 24 else "blood"   # tongue, and a bite on the chest
        return "sequin"
    if c == "#3e2654":
        return "dress"
    if c == "#a8a184":
        return "skin"
    if c == "#475367":
        return "skin_far" if y >= 6 else "hair"
    return "line"


HORDE_DROP = (63, 66, 68, 70, 74)


# Rows dropped to bring the figure to the player's height (78). Vertical runs only: the
# torso and the long shins, where a row can go without breaking a shape.
SHAMBLER_DROP = (40, 45, 63, 67, 71)


def material_map(ref_path: str, regions, drop=()) -> list[list[str | None]]:
    im = Image.open(ref_path).convert("RGBA")
    im = im.crop(im.getbbox())
    px = im.load()
    rows = []
    for y in range(im.height):
        if y in drop:
            continue
        row = []
        for x in range(im.width):
            p = px[x, y]
            row.append(regions("#%02x%02x%02x" % p[:3], x, y) if p[3] else None)
        rows.append(row)
    return rows


def render(m):
    """Shade each material on its ramp, lit from the top left, with inner lines and a
    one-pixel contour."""
    H, W = len(m), len(m[0])
    at = lambda x, y: m[y][x] if 0 <= x < W and 0 <= y < H else None
    out = [[None] * W for _ in range(H)]
    # Where each pixel sits across its run of one material: 0 at the lit left edge, 1 at the
    # right. Runs change width row to row, so t is averaged over the same material in the
    # rows above and below; without that the light bands come out with ragged edges.
    tr = [[None] * W for _ in range(H)]
    for y in range(H):
        x = 0
        while x < W:
            x1 = x
            while x1 < W and m[y][x1] == m[y][x]:
                x1 += 1
            for xx in range(x, x1):
                tr[y][xx] = (xx - x + 0.5) / (x1 - x)
            x = x1
    ts = [[None] * W for _ in range(H)]
    for y in range(H):
        for x in range(W):
            if m[y][x] is None:
                continue
            v = [tr[yy][x] for yy in range(max(0, y - 2), min(H, y + 3)) if m[yy][x] == m[y][x]]
            ts[y][x] = sum(v) / len(v)
    for y in range(H):
        x = 0
        while x < W:
            mat = m[y][x]
            x1 = x
            while x1 < W and m[y][x1] == mat:
                x1 += 1
            if mat is not None:
                for xx in range(x, x1):
                    if mat == "line":
                        out[y][xx] = OUT
                        continue
                    r = RAMPS[mat]
                    if mat in FLAT:
                        out[y][xx] = r[2]
                        continue
                    t = ts[y][xx]
                    s = 3 if t < 0.22 else 2 if t < 0.62 else 1
                    up = at(xx, y - 1)
                    if up != mat and up not in (None,):
                        s = min(3, s + 1)                  # top edge catches the light
                    down = at(xx, y + 1)
                    if down not in (mat, None, "line"):
                        s = 0                              # coloured inner line over the next material
                    elif down in (None, "line") and s > 1:
                        s -= 1                             # underside turns away from the light
                    out[y][xx] = r[s]
            x = x1
    # one-pixel contour: everything transparent that touches the figure
    for y in range(H):
        for x in range(W):
            if m[y][x] is None and any(at(x + dx, y + dy) not in (None,) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                out[y][x] = OUT
    # drop an outer contour pixel whose inward pixel is contour too (the reference has its own)
    get = lambda x, y: out[y][x] if 0 <= x < W and 0 <= y < H else None
    drop = []
    for y in range(H):
        for x in range(W):
            if out[y][x] != OUT:
                continue
            # never the only contour of a coloured pixel on another side (at a corner)
            if any(get(x + dx, y + dy) not in (None, OUT) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                if get(x + dx, y + dy) is None and get(x - dx, y - dy) == OUT \
                        and get(x - 2 * dx, y - 2 * dy) not in (None, OUT):
                    drop.append((x, y))
                    break
    for x, y in drop:
        out[y][x] = None
    fill_pockets(out)
    clean_corners(out)
    return out


def clean_corners(out):
    """Pixel-perfect contour: drop an outer contour pixel that sits in an L-shaped turn (two
    perpendicular contour neighbours, the pixel between them filled, the other two sides empty).
    The line then turns on a clean diagonal step, and nothing inside is left uncovered."""
    H, W = len(out), len(out[0])
    get = lambda x, y: out[y][x] if 0 <= x < W and 0 <= y < H else None
    for _ in range(2):
        drop = []
        for y in range(H):
            for x in range(W):
                if out[y][x] != OUT:
                    continue
                for dx, dy in ((1, 1), (1, -1), (-1, 1), (-1, -1)):
                    if get(x + dx, y) == OUT and get(x, y + dy) == OUT and get(x + dx, y + dy) is not None \
                            and get(x - dx, y) is None and get(x, y - dy) is None:
                        drop.append((x, y))
                        break
        for x, y in drop:
            out[y][x] = None


def fill_pockets(out, most=12):
    """Close small enclosed pockets of empty pixels (between an arm and the body, between the
    knees) with the contour colour: a few see-through pixels inside a figure read as specks.
    Larger enclosed gaps are real negative space and stay."""
    H, W = len(out), len(out[0])
    outside = set()
    st = [(x, y) for x in range(W) for y in (0, H - 1)] + [(x, y) for y in range(H) for x in (0, W - 1)]
    st = [p for p in st if out[p[1]][p[0]] is None]
    outside.update(st)
    while st:
        x, y = st.pop()
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < W and 0 <= ny < H and (nx, ny) not in outside and out[ny][nx] is None:
                outside.add((nx, ny))
                st.append((nx, ny))
    seen = set()
    for y in range(H):
        for x in range(W):
            if out[y][x] is not None or (x, y) in outside or (x, y) in seen:
                continue
            comp, st = [], [(x, y)]
            seen.add((x, y))
            while st:
                cx, cy = st.pop()
                comp.append((cx, cy))
                for nx, ny in ((cx + 1, cy), (cx - 1, cy), (cx, cy + 1), (cx, cy - 1)):
                    if 0 <= nx < W and 0 <= ny < H and (nx, ny) not in seen and out[ny][nx] is None:
                        seen.add((nx, ny))
                        st.append((nx, ny))
            if len(comp) <= most:
                for cx, cy in comp:
                    out[cy][cx] = OUT


def to_image_full(px) -> Image.Image:
    """The rendered pixels as an image, uncropped (same coordinates as the map)."""
    H, W = len(px), len(px[0])
    im = Image.new("RGBA", (W, H))
    for y in range(H):
        for x in range(W):
            if px[y][x]:
                h = px[y][x]
                im.putpixel((x, y), (int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16), 255))
    return im


def to_image(px) -> Image.Image:
    H, W = len(px), len(px[0])
    im = Image.new("RGBA", (W, H))
    for y in range(H):
        for x in range(W):
            if px[y][x]:
                h = px[y][x]
                im.putpixel((x, y), (int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16), 255))
    return im.crop(im.getbbox())


KINDS = {"shambler": (shambler_regions, SHAMBLER_DROP), "horde": (horde_regions, HORDE_DROP)}


def main() -> None:
    kind, ref, out = sys.argv[1:4]
    regions, drop = KINDS[kind]
    m = material_map(ref, regions, drop)
    # a pixel of room all round, so a figure touching the edge still gets its contour
    m = [[None] * (len(m[0]) + 2)] + [[None] + row + [None] for row in m] + [[None] * (len(m[0]) + 2)]
    to_image(render(m)).save(out)


if __name__ == "__main__":
    main()
