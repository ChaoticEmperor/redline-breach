"""Build our own infected (assets-debt I1) from our own pixelgen reference.

The reference (generated by pixelgen from our prompt, Apache-2.0 model, sidecar beside it)
gives only the layout: which pixel is head, shirt, arm, trousers or line. Everything you see
is ours: the materials are re-coloured on our ramps, shaded lit from the top left, given
coloured inner lines where materials meet and a one-pixel dark contour, and cut to the
player's height. The result goes into Tandem for the hand pass, and is checked with
`tools/critique_sprite.py`.

    python3 tools/draw_infected.py shambler <reference_lock.png> out.png
"""
from __future__ import annotations

import sys

from PIL import Image

OUT = "#030102"
RAMPS = {  # dark → light
    "skin":   ["#34432f", "#526848", "#71886a", "#97ab87"],
    "skin_far": ["#2a3526", "#34432f", "#526848", "#71886a"],   # the arm in shadow
    "hair":   ["#15161d", "#24262f", "#363a46", "#4a4f5c"],
    "shirt":  ["#2e1226", "#55203f", "#7e3361", "#a8508a"],
    "belt":   ["#141418", "#1e1d22", "#2a282e", "#36343a"],
    "pants":  ["#141420", "#222838", "#303a50", "#414c63"],
    "shoe":   ["#121114", "#1d1b20", "#2a272d", "#38343b"],
    "blood":  ["#3a0b0e", "#5e1418", "#86211f", "#a8342a"],
    "mouth":  ["#1a0a0c", "#2c1214", "#3e1a1c", "#3e1a1c"],
    "eye":    ["#b3ab78", "#b3ab78", "#d6cf98", "#d6cf98"],
}
FLAT = {"mouth", "eye", "line"}


# --- the shambler: regions of reference 1941657839 (see the README in assets/raw/ref_infected)
def shambler_regions(c: str, x: int, y: int) -> str | None:
    """Material for a reference pixel of colour c at (x, y), in the cropped reference."""
    line = {"#171520", "#1d212b", "#0a0612"}
    if c in line:
        if y <= 22 and 24 <= x <= 32 and y >= 20:
            return "mouth"            # the open jaw is drawn as line in the reference
        return "line"
    if c == "#fcefcd":
        return "eye"
    if c == "#ff2a6d":
        return "blood"
    if y >= 76:
        return "shoe"
    if y <= 21:
        if c in ("#475367", "#444f64", "#3e2654", "#2c202e"):
            return "hair"
        return "skin"
    if c in ("#3e2654", "#2c202e") and y >= 50:
        return "belt" if y <= 51 and c == "#2c202e" else "pants"
    if c == "#2c202e" and y <= 22:
        return "mouth"
    if c == "#a8a184":
        if y >= 52 and 8 < x < 13:
            return "pants"            # hem hidden behind the hand: trousers once the hand moves
        if y >= 35 and x <= 8:
            return "skin"             # near forearm and hand
        if y <= 25 and x >= 22:
            return "skin"             # neck and chin
        return "shirt"
    if c in ("#475367", "#444f64"):
        if x >= 22 and y >= 34:
            return "skin_far"         # far arm, in shadow
        if y <= 25:
            return "skin_far"         # nape under the hair
        return "shirt"
    if c == "#3e2654":
        return "shirt"
    return "shirt"


# Rows dropped to bring the figure to the player's height (78). Vertical runs only: the
# torso and the long shins, where a row can go without breaking a shape.
SHAMBLER_DROP = (40, 45, 63, 67, 71)


def material_map(ref_path: str, regions, drop=()) -> list[list[str | None]]:
    im = Image.open(ref_path).convert("RGBA")
    im = im.crop(im.getbbox())
    px = im.load()
    rows = []
    for y in range(im.height):
        if y in drop:
            continue
        row = []
        for x in range(im.width):
            p = px[x, y]
            row.append(regions("#%02x%02x%02x" % p[:3], x, y) if p[3] else None)
        rows.append(row)
    return rows


def render(m):
    """Shade each material on its ramp, lit from the top left, with inner lines and a
    one-pixel contour."""
    H, W = len(m), len(m[0])
    at = lambda x, y: m[y][x] if 0 <= x < W and 0 <= y < H else None
    out = [[None] * W for _ in range(H)]
    # Where each pixel sits across its run of one material: 0 at the lit left edge, 1 at the
    # right. Runs change width row to row, so t is averaged over the same material in the
    # rows above and below; without that the light bands come out with ragged edges.
    tr = [[None] * W for _ in range(H)]
    for y in range(H):
        x = 0
        while x < W:
            x1 = x
            while x1 < W and m[y][x1] == m[y][x]:
                x1 += 1
            for xx in range(x, x1):
                tr[y][xx] = (xx - x + 0.5) / (x1 - x)
            x = x1
    ts = [[None] * W for _ in range(H)]
    for y in range(H):
        for x in range(W):
            if m[y][x] is None:
                continue
            v = [tr[yy][x] for yy in range(max(0, y - 2), min(H, y + 3)) if m[yy][x] == m[y][x]]
            ts[y][x] = sum(v) / len(v)
    for y in range(H):
        x = 0
        while x < W:
            mat = m[y][x]
            x1 = x
            while x1 < W and m[y][x1] == mat:
                x1 += 1
            if mat is not None:
                for xx in range(x, x1):
                    if mat == "line":
                        out[y][xx] = OUT
                        continue
                    r = RAMPS[mat]
                    if mat in FLAT:
                        out[y][xx] = r[2]
                        continue
                    t = ts[y][xx]
                    s = 3 if t < 0.22 else 2 if t < 0.62 else 1
                    up = at(xx, y - 1)
                    if up != mat and up not in (None,):
                        s = min(3, s + 1)                  # top edge catches the light
                    down = at(xx, y + 1)
                    if down not in (mat, None, "line"):
                        s = 0                              # coloured inner line over the next material
                    elif down in (None, "line") and s > 1:
                        s -= 1                             # underside turns away from the light
                    out[y][xx] = r[s]
            x = x1
    # one-pixel contour: everything transparent that touches the figure
    for y in range(H):
        for x in range(W):
            if m[y][x] is None and any(at(x + dx, y + dy) not in (None,) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                out[y][x] = OUT
    # drop an outer contour pixel whose inward pixel is contour too (the reference has its own)
    get = lambda x, y: out[y][x] if 0 <= x < W and 0 <= y < H else None
    drop = []
    for y in range(H):
        for x in range(W):
            if out[y][x] != OUT:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                if get(x + dx, y + dy) is None and get(x - dx, y - dy) == OUT \
                        and get(x - 2 * dx, y - 2 * dy) not in (None, OUT):
                    drop.append((x, y))
                    break
    for x, y in drop:
        out[y][x] = None
    return out


def to_image_full(px) -> Image.Image:
    """The rendered pixels as an image, uncropped (same coordinates as the map)."""
    H, W = len(px), len(px[0])
    im = Image.new("RGBA", (W, H))
    for y in range(H):
        for x in range(W):
            if px[y][x]:
                h = px[y][x]
                im.putpixel((x, y), (int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16), 255))
    return im


def to_image(px) -> Image.Image:
    H, W = len(px), len(px[0])
    im = Image.new("RGBA", (W, H))
    for y in range(H):
        for x in range(W):
            if px[y][x]:
                h = px[y][x]
                im.putpixel((x, y), (int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16), 255))
    return im.crop(im.getbbox())


KINDS = {"shambler": (shambler_regions, SHAMBLER_DROP)}


def main() -> None:
    kind, ref, out = sys.argv[1:4]
    regions, drop = KINDS[kind]
    to_image(render(material_map(ref, regions, drop))).save(out)


if __name__ == "__main__":
    main()
